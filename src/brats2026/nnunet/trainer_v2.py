@dataclass
class GoATTrainerConfigV2:
    """Hyperparameters for ``nnUNetTrainerGoATv2`` — every ``# SPECIALIST:`` hook, plus 2 choices.

    Defaults are ``None`` on purpose: ``None`` means "not yet decided by the specialist".
    Reference values live in the comments only, never silently applied. ``init_weights_from`` and
    ``init_weights_strict`` are choices (see :data:`SPECIALIST_HOOKS_V2`), so they are excluded
    from the hook tuple and ``None`` leaves them inert.
    """

    # --- optimiser / schedule ---
    initial_lr: Optional[float] = None            # SPECIALIST: nnU-Net default 1e-2; LOWER when warm-starting a converged model
    weight_decay: Optional[float] = None          # SPECIALIST: nnU-Net default 3e-5
    num_epochs: Optional[int] = None              # SPECIALIST: nnU-Net default 1000; a warm start needs far fewer
    batch_size: Optional[int] = None              # SPECIALIST: planner-derived; watch A10G 24GB
    patch_size: Optional[tuple[int, int, int]] = None  # SPECIALIST: planner-derived
    oversample_foreground_percent: Optional[float] = None  # SPECIALIST: nnU-Net default 0.33
    loss_dice_weight: Optional[float] = None      # SPECIALIST: region Dice weight
    loss_ce_weight: Optional[float] = None        # SPECIALIST: region BCE/CE weight

    # --- domain randomisation (override nnU-Net's default DA probabilities) ---
    da_scale_range: Optional[tuple[float, float]] = None  # SPECIALIST: scale aug range; widen for small paediatric brains / sub-cm mets
    da_noise_p: Optional[float] = None            # SPECIALIST: additive Gaussian-noise probability
    da_blur_p: Optional[float] = None             # SPECIALIST: Gaussian-blur probability
    da_brightness_p: Optional[float] = None       # SPECIALIST: multiplicative-brightness probability
    da_contrast_p: Optional[float] = None         # SPECIALIST: contrast-jitter probability
    da_low_res_p: Optional[float] = None          # SPECIALIST: low-resolution simulation probability (thick-slice / low-field proxy)
    da_gamma_p: Optional[float] = None            # SPECIALIST: gamma-correction probability

    # --- bias field (MRI-specific; not in nnU-Net's default pipeline) ---
    da_bias_field_p: Optional[float] = None       # SPECIALIST: bias-field probability
    da_bias_field_order: Optional[int] = None     # SPECIALIST: polynomial order of the field, ~3
    da_bias_field_coeff_range: Optional[tuple[float, float]] = None  # SPECIALIST: polynomial coefficient range

    # --- CHOICES (NOT hooks; None is legal and means "no warm start") ---
    init_weights_from: Optional[str] = None       # CHOICE: path to a checkpoint from one of OUR OWN GoAT runs
    init_weights_strict: bool = False             # CHOICE: require every model key to be present in the checkpoint


def unset_hooks(config: GoATTrainerConfigV2) -> list[str]:
    """Return the names of SPECIALIST hooks still ``None`` (i.e. not yet decided).

    Filters on :data:`SPECIALIST_HOOKS_V2` rather than every dataclass field, so the
    ``init_weights_*`` choices are never reported as missing.
    """
    return [
        f.name
        for f in fields(config)
        if f.name in SPECIALIST_HOOKS_V2 and getattr(config, f.name) is None
    ]


def assert_configured(config: GoATTrainerConfigV2) -> None:
    """Raise if any SPECIALIST hook is unset — a guard before launching a real v2 run."""
    missing = unset_hooks(config)
    if missing:
        raise ValueError(
            "Refusing to launch nnUNetTrainerGoATv2: the AI specialist must set these "
            f"# SPECIALIST hooks first: {', '.join(missing)}"
        )


# --- warm start (pure; the transfer contract is unit-testable without torch) ----------------

@dataclass(frozen=True)
class WeightTransferPlan:
    """What a checkpoint can and cannot contribute to a freshly-built model.

    ``transferable`` are the keys present in both with identical shapes — the only ones that may
    be loaded. The other three fields exist so a partial or wrong transfer is *reported*, never
    inferred from silence.
    """

    transferable: list[str]
    shape_mismatched: list[str]
    missing_in_checkpoint: list[str]
    unexpected_in_checkpoint: list[str]


def plan_weight_transfer(checkpoint_shapes: dict, model_shapes: dict) -> WeightTransferPlan:
    """Compare a checkpoint's ``{key: shape}`` against a model's and classify every key.

    Shapes are compared as tuples, so this works on ``{k: tuple(v.shape)}`` extracted from a real
    ``state_dict`` without importing torch. Results are sorted for deterministic reporting.
    """
    transferable, mismatched, missing = [], [], []
    for key, shape in model_shapes.items():
        if key not in checkpoint_shapes:
            missing.append(key)
        elif tuple(checkpoint_shapes[key]) == tuple(shape):
            transferable.append(key)
        else:
            mismatched.append(key)
    unexpected = [k for k in checkpoint_shapes if k not in model_shapes]
    return WeightTransferPlan(
        transferable=sorted(transferable),
        shape_mismatched=sorted(mismatched),
        missing_in_checkpoint=sorted(missing),
        unexpected_in_checkpoint=sorted(unexpected),
    )


def assert_transferable(plan: WeightTransferPlan, strict: bool = False) -> None:
    """Refuse a warm start that would quietly degrade into a random initialisation.

    Always raises when **nothing** transfers (the wrong checkpoint was pointed at) or when any
    shape differs (the architectures are not the same, so the transfer is not what it claims).
    With ``strict`` it additionally requires the checkpoint to cover every model tensor.
    """
    if not plan.transferable:
        raise ValueError(
            "Refusing the warm start: no tensor in the checkpoint matches this model "
            f"({len(plan.missing_in_checkpoint)} model key(s) absent, "
            f"{len(plan.unexpected_in_checkpoint)} checkpoint key(s) unused). "
            "Check init_weights_from points at a run with the same plans / configuration."
        )
    if plan.shape_mismatched:
        sample = ", ".join(plan.shape_mismatched[:3])
        raise ValueError(
            f"Refusing the warm start: {len(plan.shape_mismatched)} tensor(s) differ in shape "
            f"(e.g. {sample}). The checkpoint was produced by a different architecture."
        )
    if strict and plan.missing_in_checkpoint:
        sample = ", ".join(plan.missing_in_checkpoint[:3])
        raise ValueError(
            f"Refusing the warm start under init_weights_strict: {len(plan.missing_in_checkpoint)} "
            f"model tensor(s) are absent from the checkpoint (e.g. {sample})."
        )


def config_from_mapping(cfg: dict) -> GoATTrainerConfigV2:
    """Build a :class:`GoATTrainerConfigV2` from a train_v2-config mapping (a loaded YAML).

    Reads :data:`SPECIALIST_HOOKS_V2` plus the :data:`_CHOICE_KEYS`; list-valued tuple hooks are
    coerced from YAML lists to tuples. Missing / ``None`` keys stay ``None`` so
    :func:`unset_hooks` / :func:`assert_configured` still gate an unfilled config.
    """
    kwargs: dict = {}
    for key in SPECIALIST_HOOKS_V2 + _CHOICE_KEYS:
        value = cfg.get(key)
        if value is None:
            continue
        if key in _TUPLE_HOOKS and isinstance(value, list):
            value = tuple(value)
        kwargs[key] = value
    return GoATTrainerConfigV2(**kwargs)


def load_goat_v2_config(path: str | Path) -> GoATTrainerConfigV2:
    """Load, VALIDATE and build a :class:`GoATTrainerConfigV2` from a ``configs/train_v2.yaml``.

    Provenance-header + all-hooks validation is delegated to
    :func:`brats2026.config.assert_valid_config` with kind ``"train_v2"``, so an unfilled or
    unstamped config is refused BEFORE any training starts. The import is local so this module
    stays import-light (``brats2026.config`` imports *us* at module scope).
    """
    from ..config import assert_valid_config, load_config

    cfg = load_config(Path(path))
    assert_valid_config(cfg, "train_v2")
    return config_from_mapping(cfg)


def apply_goat_v2_config(trainer, config: GoATTrainerConfigV2) -> None:
    """Copy the directly-mappable SPECIALIST numbers onto a live ``nnUNetTrainer``.

    Sets the four standard nnU-Net attributes and MUST run before ``super().initialize()`` so the
    optimizer and dataloaders pick them up. ``batch_size`` / ``patch_size`` come from the plans,
    not here; the ``da_*`` values are consumed by :meth:`nnUNetTrainerGoATv2.get_training_transforms`.
    Duck-typed on ``trainer`` so it is unit-testable without nnU-Net installed.
    """
    assert_configured(config)
    trainer.initial_lr = config.initial_lr
    trainer.weight_decay = config.weight_decay
    trainer.num_epochs = config.num_epochs
    trainer.oversample_foreground_percent = config.oversample_foreground_percent


def install_goat_trainer_v2() -> str:
    """Drop an import shim into nnU-Net's trainer tree so ``-tr nnUNetTrainerGoATv2`` resolves.

    Writes :data:`GOAT_V2_SHIM_BODY` to :data:`GOAT_V2_SHIM_NAME`, a filename distinct from the v1
    shim so an in-flight v1 run keeps the trainer it started with. Returns the shim path;
    idempotent. Requires nnU-Net installed (import is local so the module stays import-light).
    """
    import nnunetv2

    variants = Path(nnunetv2.__file__).parent / "training" / "nnUNetTrainer" / "variants"
    variants.mkdir(parents=True, exist_ok=True)
    shim = variants / GOAT_V2_SHIM_NAME
    shim.write_text(GOAT_V2_SHIM_BODY, encoding="utf-8")
    return str(shim)


# --- bias field (pure; the one MRI corruption nnU-Net's default DA does not model) ----------

def bias_field_term_count(order: int, ndim: int = 3) -> int:
    """Number of polynomial terms of total degree ``<= order`` in ``ndim`` variables.

    ``comb(order + ndim, ndim)`` — e.g. 20 terms for the cubic 3-D field the config defaults to.
    This is exactly how many coefficients :func:`bias_field_multiplier` consumes.
    """
    from math import comb

    if order < 0:
        raise ValueError(f"order must be >= 0, got {order}")
    return comb(order + ndim, ndim)


def _bias_field_exponents(order: int, ndim: int) -> list[tuple[int, ...]]:
    """Exponent tuples of total degree ``<= order``, ordered deterministically.

    Sorted by (total degree, lexicographic) so a given coefficient vector always maps to the same
    polynomial — the field must be reproducible from a seed, not just from an object identity.
    """
    from itertools import product

    exponents = [e for e in product(range(order + 1), repeat=ndim) if sum(e) <= order]
    exponents.sort(key=lambda e: (sum(e), e))
    return exponents


def bias_field_multiplier(shape, order: int, coefficients):
    """Build a smooth, strictly-positive multiplicative bias field of ``shape``.

    Models the slow intensity inhomogeneity a real MR scanner imprints on a volume — the coil
    sensitivity roll-off that makes one side of a brain brighter than the other. nnU-Net's stock
    augmentation pipeline has noise, blur, brightness, contrast, low-res and gamma but **no**
    bias field, so this is the one genuinely new corruption v2 adds.

    The field is ``exp(mean_k(c_k * x^a_k y^b_k z^c_k))`` over normalised coordinates in
    ``[-1, 1]``:

    - the ``exp`` makes it **strictly positive**, so multiplying an image can never flip or
      annihilate an intensity;
    - all-zero coefficients give an **identity** (all-ones) field, so "off" is expressible;
    - averaging over the terms rather than summing keeps the coefficient range meaning the same
      thing at any ``order`` — a coefficient of 0.1 is ~10% log-amplitude whether the polynomial
      has 4 terms or 20. That is what lets ``da_bias_field_coeff_range`` be tuned independently
      of ``da_bias_field_order``.

    ``coefficients`` must hold at least :func:`bias_field_term_count` values (extras are ignored);
    too few raises, because a short vector would silently truncate the polynomial to a lower
    order than requested. numpy is imported locally so the module stays import-light.
    """
    import numpy as np

    shape = tuple(int(n) for n in shape)
    ndim = len(shape)
    needed = bias_field_term_count(order, ndim)
    coefficients = list(coefficients)
    if len(coefficients) < needed:
        raise ValueError(
            f"bias field of order {order} in {ndim}D needs {needed} coefficients, "
            f"got {len(coefficients)}"
        )

    # A length-1 axis has no extent to vary over; pin it at the field centre rather than at -1.
    axes = [np.linspace(-1.0, 1.0, n) if n > 1 else np.zeros(1) for n in shape]
    grids = np.meshgrid(*axes, indexing="ij")

    log_field = np.zeros(shape, dtype=np.float64)
    for coefficient, exponents in zip(coefficients, _bias_field_exponents(order, ndim)):
        term = np.ones(shape, dtype=np.float64)
        for grid, exponent in zip(grids, exponents):
            if exponent:
                term = term * grid**exponent
        log_field += coefficient * term
    log_field /= needed
    return np.exp(log_field)


def sample_bias_field_coefficients(order: int, coeff_range, rng, ndim: int = 3) -> list[float]:
    """Draw one coefficient per polynomial term, uniform in ``coeff_range``, with random signs.

    ``coeff_range`` bounds the *magnitude* (it is a SPECIALIST hook expressed as a positive
    range); the sign is randomised here so the field brightens some volumes and darkens others
    instead of always pulling the same direction. ``rng`` is any object with ``uniform`` and
    ``random`` — a seeded :class:`random.Random` in tests, numpy's generator at train time.
    """
    low, high = float(coeff_range[0]), float(coeff_range[1])
    count = bias_field_term_count(order, ndim)
    return [rng.uniform(low, high) * (1.0 if rng.random() < 0.5 else -1.0) for _ in range(count)]


# --- augmentation retuning (pure; testable against dummy transforms, no nnU-Net needed) -----

# Side length of the grid the bias field is evaluated on before trilinear upsampling to the patch.
# The field is a low-order polynomial and therefore smooth by construction, so evaluating it
# coarsely and interpolating is near-exact. Measured on this repo at order 3, coefficients 0.12,
# against a direct evaluation at a 128x160x112 patch: max relative error 0.013%, while the
# polynomial evaluation drops from ~840 ms to ~2 ms. That matters because this runs inside the
# dataloader on every augmented sample — at patch resolution it would dominate training time.
BIAS_FIELD_EVAL_GRID = 32

# Hook name -> the batchgeneratorsv2 transform classes whose probability it overrides. nnU-Net
# wraps each optional augmentation in a RandomTransform carrying `apply_probability`, so the
# override target is the WRAPPER, keyed by the class name of the transform it wraps.
#
# Several candidates per hook because the base trainer is nnUNetTrainerDA5, which uses different
# classes from the stock trainer for the same intent (additive rather than multiplicative
# brightness, a median-filter/blur choice rather than a bare blur). A hook binds to whichever
# candidate the base pipeline actually built; one that binds to none is REPORTED, not ignored.
DA_PROBABILITY_HOOKS: dict[str, tuple[str, ...]] = {
    "da_noise_p": ("GaussianNoiseTransform",),
    "da_blur_p": ("GaussianBlurTransform", "MedianFilterTransform"),
    "da_brightness_p": ("MultiplicativeBrightnessTransform", "BrightnessAdditiveTransform"),
    "da_contrast_p": ("ContrastTransform",),
    "da_low_res_p": ("SimulateLowResolutionTransform",),
    "da_gamma_p": ("GammaTransform",),
    "da_bias_field_p": ("BiasFieldTransform",),
}


def _walk_transforms(node):
    """Yield every transform in a (possibly nested) batchgeneratorsv2 transform tree.

    Duck-typed on a ``transforms`` list (ComposeTransforms) and a ``transform`` attribute
    (RandomTransform), so the walk works on real nnU-Net objects and on test doubles alike.
    """
    yield node
    children = getattr(node, "transforms", None)
    if isinstance(children, (list, tuple)):
        for child in children:
            yield from _walk_transforms(child)
    wrapped = getattr(node, "transform", None)
    if wrapped is not None:
        yield from _walk_transforms(wrapped)


def retune_augmentation(transforms, config: GoATTrainerConfigV2) -> dict[str, object]:
    """Rewrite nnU-Net's default augmentation strengths in place from the SPECIALIST hooks.

    Two distinct edits, both **overrides** rather than additions (a probability hook replaces
    nnU-Net's default probability, it does not compose with it):

    - every ``da_*_p`` hook sets ``apply_probability`` on the ``RandomTransform`` wrapping the
      class named in :data:`DA_PROBABILITY_HOOKS`;
    - ``da_scale_range`` replaces ``SpatialTransform.scaling``, which is what widens the range of
      brain sizes the model sees (paediatric brains and sub-cm metastases are the motivating
      cases, and PED has no training data at all).

    Returns a report of what was actually retuned so :meth:`nnUNetTrainerGoATv2.get_training_
    transforms` can log it. A hook that matched nothing is reported as missing rather than
    silently ignored — a renamed transform class upstream must not quietly disable an override.
    """
    report: dict[str, object] = {"retuned": {}, "missing": []}
    by_class = {name: hook for hook, names in DA_PROBABILITY_HOOKS.items() for name in names}
    matched: set[str] = set()

    for node in _walk_transforms(transforms):
        wrapped = getattr(node, "transform", None)
        if wrapped is not None and hasattr(node, "apply_probability"):
            # DA5 wraps alternatives in a OneOfTransform, so the RandomTransform's direct child is
            # the group, not the augmentation. Look one level into any group before giving up.
            candidates = [wrapped]
            group = getattr(wrapped, "transforms", None)
            if isinstance(group, (list, tuple)):
                candidates.extend(group)
            # nnU-Net ships TWO GammaTransforms: an INVERTED pass (p_invert_image=1, stock 0.10)
            # and a plain one (p_invert_image=0, stock 0.30). da_gamma_p names the plain one only.
            # Matching on class name alone would raise the inverted pass to the same value —
            # a 4.5x jump nobody asked for, invisible in the logs, and it would silently make the
            # v1-vs-v2 delta a two-variable change.
            candidates = [
                c for c in candidates
                if not (type(c).__name__ == "GammaTransform" and getattr(c, "p_invert_image", 0))
            ]
            hook = next((by_class[type(c).__name__] for c in candidates
                         if type(c).__name__ in by_class), None)
            if hook is not None:
                value = getattr(config, hook)
                if value is not None:
                    node.apply_probability = float(value)
                    report["retuned"][hook] = float(value)  # type: ignore[index]
                    matched.add(hook)
        if type(node).__name__ == "SpatialTransform" and config.da_scale_range is not None:
            node.scaling = tuple(config.da_scale_range)
            report["retuned"]["da_scale_range"] = tuple(config.da_scale_range)  # type: ignore[index]
            matched.add("da_scale_range")

    for hook in list(DA_PROBABILITY_HOOKS) + ["da_scale_range"]:
        if getattr(config, hook) is not None and hook not in matched:
            report["missing"].append(hook)  # type: ignore[union-attr]
    return report


# --- warm start (torch) ---------------------------------------------------------------------

def load_warm_start_weights(model, checkpoint_path: str | Path, strict: bool = False):
    """Seed ``model`` from one of OUR OWN converged GoAT checkpoints, or refuse loudly.

    The transfer is planned on shapes first (:func:`plan_weight_transfer`) and gated by
    :func:`assert_transferable`, so the failure mode that costs GPU-days — pointing at a
    checkpoint from different plans, getting a near-empty load, and training from what is
    effectively a random init without noticing — raises instead of proceeding. Only the tensors
    the plan marked ``transferable`` are copied; nothing is loaded partially by shape coercion.

    Returns the :class:`WeightTransferPlan` so the caller can log the coverage. torch is imported
    locally so this module still imports in a bare environment.
    """
    import torch

    checkpoint = torch.load(str(checkpoint_path), map_location="cpu", weights_only=False)
    # nnU-Net writes {'network_weights': state_dict, ...}; a bare state_dict is also accepted.
    state = checkpoint
    for key in ("network_weights", "state_dict", "model_state_dict"):
        if isinstance(checkpoint, dict) and key in checkpoint:
            state = checkpoint[key]
            break
    if not isinstance(state, dict):
        raise ValueError(f"{checkpoint_path} did not contain a state_dict-like mapping")

    model_state = model.state_dict()
    plan = plan_weight_transfer(
        {k: tuple(v.shape) for k, v in state.items() if hasattr(v, "shape")},
        {k: tuple(v.shape) for k, v in model_state.items()},
    )
    assert_transferable(plan, strict=strict)
    model.load_state_dict({k: state[k] for k in plan.transferable}, strict=False)
    return plan


def resolve_v2_config(config: GoATTrainerConfigV2) -> GoATTrainerConfigV2:
    """Return ``config`` if already filled, else load the one named by the v2 env var.

    nnU-Net resolves a trainer by NAME and cannot be handed an object, so a filled
    ``configs/train_v2.yaml`` reaches the trainer through
    :data:`GOAT_V2_TRAIN_CONFIG_ENV`. Split out of the trainer class so the
    resolution order (class attribute wins, env var is the fallback) is testable without
    nnU-Net installed. Raises via :func:`assert_configured` if neither source fills the hooks.
    """
    if unset_hooks(config):
        env_path = os.environ.get(GOAT_V2_TRAIN_CONFIG_ENV)
        if env_path:
            config = load_goat_v2_config(env_path)
    assert_configured(config)
    return config


