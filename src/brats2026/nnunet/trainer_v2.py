"""Phase 7 — ``nnUNetTrainerGoATv2``: a warm-started, domain-randomised GoAT trainer.

This is a **second, independent** trainer that lives alongside :mod:`brats2026.nnunet.trainer`.
It exists because hyperparameter tuning has saturated (submission 1 already sits at
top-leaderboard parity; successive runs move the score by ~1e-2 to 1e-3), while Task 3 is scored
on *generalisation* — and two of the five cohorts (SSA, PED) have **no training data at all**
(``docs/synapse_wiki_raw/Task3_data.md``). The remaining lever is augmentation, not tuning.

v2 therefore

- **warm-starts** from an already-converged GoAT run's checkpoint (``init_weights_from``), so a
  fold that v1 has finished can be improved without paying for training from scratch again, and
- inherits **nnU-Net's own aggressive-augmentation variant** ``nnUNetTrainerDA5`` as its base
  class, rather than hand-tuning probabilities on top of the stock pipeline.

The DA5 decision is deliberate and was a correction: DA5 already ships
``BrightnessGradientAdditiveTransform`` and ``LocalGammaTransform`` at p=0.3, which is
spatially-varying intensity corruption — the same intent as the bias field this module also
implements, but validated in DKFZ's own challenge entries. Building on it means the augmentation
is DKFZ's, and only the warm start, the config gate and the retuning hooks are ours.

**Why a separate module and not new hooks on v1.** :data:`brats2026.config.TRAIN_HOOK_KEYS` is a
verbatim alias of :data:`brats2026.nnunet.trainer.SPECIALIST_HOOKS`, so adding one hook there
would immediately make the *in-flight* ``configs/train.yaml`` invalid (the new key would read as
unset) and the running job would refuse to restart. v1 is therefore strictly untouched. nnU-Net
also derives its output directory from ``<trainer>__<plans>__<configuration>``, so a distinct
class name keeps v2's results from colliding with the folds still training.

**GoAT rule compliance.** Warm-starting from *our own* GoAT-trained weights is allowed: the rule
forbids external data and weights derived from a **prior BraTS**, not resuming one of our own
runs. Nothing here initialises from an external corpus. The hook is named ``init_weights_from``
rather than ``pretrained_*`` because :data:`brats2026.compliance.PRIOR_BRATS_TOKENS` flags those
substrings, and a compliant name must not trip our own gate.

Like the rest of the package this module invents **no** numbers: every tunable is a
``# SPECIALIST:`` hook on :class:`GoATTrainerConfigV2` defaulting to ``None``. Pure functions stay
stdlib/numpy only — imported *inside* the functions — so the module and its tests load without
torch / nnU-Net (CI has neither). The concrete class is defined only when nnU-Net is importable,
mirroring :class:`brats2026.nnunet.trainer.nnUNetTrainerGoAT`.
"""
